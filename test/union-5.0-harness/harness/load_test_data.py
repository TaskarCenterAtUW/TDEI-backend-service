"""
Write the SQL that loads the harness test data into the TDEI content tables.

    python3 harness/load_test_data.py > runs/load_test_data.sql
    psql "$PGCONN" -v ON_ERROR_STOP=1 -f runs/load_test_data.sql

Loads DS1 as dataset id 'harness5-ds1' and DS2 as 'harness5-ds2' (change with
--ds1-id / --ds2-id): nodes, edges, zones and extension points, lines and
polygons, from data/ (another folder with --data-dir, e.g. demo/data). Rows already under those ids are deleted first, so it is safe to
re-run after regenerating the data. Nothing else in the tables is touched.

Matches the real TDEI tables: only (tdei_dataset_id, feature) are inserted —
ids, geometry and tag columns are GENERATED from the feature. Use a dev
database or the local Docker one (docker-compose.yml), not production.
"""
import argparse, json, os

DATA = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data")
TABLES = (("node", "nodes"), ("edge", "edges"), ("zone", "zones"),
          ("extension_point", "points"), ("extension_line", "lines"), ("extension_polygon", "polygons"))
ap = argparse.ArgumentParser()
ap.add_argument("--ds1-id", default="harness5-ds1")
ap.add_argument("--ds2-id", default="harness5-ds2")
ap.add_argument("--data-dir", default=DATA, help="folder holding ds1_*.geojson and ds2_*.geojson")
args = ap.parse_args()

def q(s): return "'" + str(s).replace("'", "''") + "'"
def feats(name):
    path = os.path.join(args.data_dir, name)
    return json.load(open(path))["features"] if os.path.exists(path) else []

ids = f"({q(args.ds1_id)}, {q(args.ds2_id)})"
print("-- generated by load_test_data.py\n\\set ON_ERROR_STOP on\nBEGIN;")
for table, _ in TABLES:
    print(f"DELETE FROM content.{table} WHERE tdei_dataset_id IN {ids};")
for ds, ds_id in (("ds1", args.ds1_id), ("ds2", args.ds2_id)):
    for table, kind in TABLES:
        for f in feats(f"{ds}_{kind}.geojson"):
            print(f"INSERT INTO content.{table} (tdei_dataset_id, feature) VALUES "
                  f"({q(ds_id)}, {q(json.dumps(f))}::json);")
print("COMMIT;")
print(" UNION ALL ".join(
    f"SELECT {q(table)} AS entity, tdei_dataset_id, COUNT(*) FROM content.{table} "
    f"WHERE tdei_dataset_id IN {ids} GROUP BY 1, 2" for table, _ in TABLES) + " ORDER BY 1, 2;")
